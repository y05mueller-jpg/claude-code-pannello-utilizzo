// Claude Code reader: counts messages and tokens from ~/.claude/projects/**/*.jsonl.
// Same logic as the Claude Code mod "utilizzo" (strumenti/conta.js), numbers only:
// message text is never stored or returned (only its length, to estimate "tokens written by you").
// Each file is read once, then only the new lines (state kept in the cache object passed in).
'use strict';
const fs = require('fs'), path = require('path');
const { giorno, leggiRighe, fileConFine, aggiungiRichiesta, aggiungiMessaggio } = require('./comune');

const VERSIONE = 1;

function leggiClaude(radice, cacheIn) {
  const cache = cacheIn && cacheIn.v === VERSIONE ? cacheIn : { v: VERSIONE, file: {}, sessioni: {} };
  const sessione = id => cache.sessioni[id] || (cache.sessioni[id] = {
    messaggi: 0, richieste: 0, token: 0, u: [0, 0, 0, 0], scritti: 0, titolo: '', titoloAi: '', progetto: '', primo: 0, ultimo: 0, giorni: {}, bloccata: false,
  });
  const visti = new Set();
  for (const file of fileConFine(radice, ['.jsonl'])) {
    visti.add(file);
    let st; try { st = fs.statSync(file); } catch (e) { continue; }
    const f = cache.file[file] || (cache.file[file] = { inizio: 0, richieste: [], mtime: 0 });
    f.mtime = st.mtimeMs;
    if (st.size < f.inizio) { f.inizio = 0; f.richieste = []; }   // file rewritten: start again
    if (st.size === f.inizio) continue;
    const secondario = file.includes(`${path.sep}subagents${path.sep}`);
    const giaContate = new Set(f.richieste);
    let letto;
    try { letto = leggiRighe(file, f.inizio); } catch (e) { continue; }
    for (const r of letto.righe) {
      if (!r) continue;
      let j; try { j = JSON.parse(r); } catch (e) { continue; }
      if (!j.sessionId) continue;
      const s = sessione(j.sessionId);
      if (!s.progetto) s.progetto = path.basename(secondario ? path.dirname(path.dirname(path.dirname(file))) : path.dirname(file));
      // titles are set by the person (custom-title) or generated by Claude Code (ai-title): not message text
      if (j.type === 'custom-title' && j.customTitle) { s.titolo = String(j.customTitle).slice(0, 80); continue; }
      if (j.type === 'ai-title' && j.aiTitle) { s.titoloAi = String(j.aiTitle).slice(0, 80); continue; }
      const ts = j.timestamp ? Date.parse(j.timestamp) : NaN;
      if (!isNaN(ts)) { if (!s.primo || ts < s.primo) s.primo = ts; if (ts > s.ultimo) s.ultimo = ts; }
      if (j.type === 'assistant' && j.message && j.message.usage) {
        const id = j.requestId || j.message.id;
        if (id && giaContate.has(id)) continue;   // the same reply is written on several lines
        if (id) { giaContate.add(id); f.richieste.push(id); }
        const u = j.message.usage;
        // Claude: input_tokens does NOT include the cache, so the four numbers add up
        aggiungiRichiesta(s, isNaN(ts) ? null : giorno(ts), u.input_tokens || 0, u.output_tokens || 0, u.cache_creation_input_tokens || 0, u.cache_read_input_tokens || 0);
        if (!s.modello && j.message.model) s.modello = String(j.message.model).slice(0, 40);
        s.bloccata = false;
        if (f.richieste.length > 50000) f.richieste = f.richieste.slice(-20000);
      } else if (j.type === 'assistant' && j.isApiErrorMessage) {
        const t = JSON.stringify(j.message || '').toLowerCase();
        s.bloccata = /limit|quota|rate/.test(t);
      } else if (!secondario && j.type === 'user' && !j.isMeta && !j.isCompactSummary) {
        const n = lunghezzaTestoUtente(j.message);
        if (n < 0) continue;
        aggiungiMessaggio(s, isNaN(ts) ? null : giorno(ts), Math.ceil(n / 4));   // ~4 characters per token
      }
    }
    f.inizio = letto.nuovoInizio;
  }
  for (const k of Object.keys(cache.file)) if (!visti.has(k)) delete cache.file[k];

  // summary in the common shape (see comune.js)
  const ultimoFile = {};
  for (const [p, f] of Object.entries(cache.file)) { const id = path.basename(p, '.jsonl'); ultimoFile[id] = Math.max(ultimoFile[id] || 0, f.mtime); }
  const sessioni = [];
  for (const [id, s] of Object.entries(cache.sessioni)) {
    if (!s.richieste && !s.messaggi) continue;
    sessioni.push({
      id, fonte: 'claude', titolo: s.titolo || s.titoloAi || '', modello: s.modello || '',
      progetto: s.progetto.replace(/^[A-Za-z]--Users-[^-]+-(Documents-)?/, '').replace(/^-home-[^-]+-/, '').replace(/-/g, ' '),
      messaggi: s.messaggi, richieste: s.richieste, token: s.token, u: s.u, scritti: s.scritti,
      ultimo: Math.max(s.ultimo, ultimoFile[id] || 0), bloccata: s.bloccata, giorni: s.giorni,
    });
  }
  return { cache, sessioni, limiti: [], avvisi: [] };
}

// length of a message written by the person (not tool results, not system notices); -1 if it is not one
function lunghezzaTestoUtente(m) {
  if (!m || m.role !== 'user') return -1;
  let t = null;
  if (typeof m.content === 'string') t = m.content;
  else if (Array.isArray(m.content) && !m.content.some(b => b && b.type === 'tool_result')) {
    const b = m.content.find(x => x && x.type === 'text');
    t = b ? b.text : null;
  }
  if (t == null || /^\s*</.test(t)) return -1;   // internal notices and commands
  return t.length;
}

module.exports = { leggiClaude };
